impl M3Palette {
    /// Lerp every colour role toward another palette.
    pub fn lerp(&self, target: &Self, t: f32) -> Self {
        fn lerp_u8(a: u8, b: u8, t: f32) -> u8 {
            (a as f32 + (b as f32 - a as f32) * t) as u8
        }
        fn lerp_c3(a: &[u8; 3], b: &[u8; 3], t: f32) -> [u8; 3] {
            [lerp_u8(a[0], b[0], t), lerp_u8(a[1], b[1], t), lerp_u8(a[2], b[2], t)]
        }

        Self {
            primary: lerp_c3(&self.primary, &target.primary, t),
            on_primary: lerp_c3(&self.on_primary, &target.on_primary, t),
            primary_container: lerp_c3(&self.primary_container, &target.primary_container, t),
            on_primary_container: lerp_c3(&self.on_primary_container, &target.on_primary_container, t),
            secondary: lerp_c3(&self.secondary, &target.secondary, t),
            on_secondary: lerp_c3(&self.on_secondary, &target.on_secondary, t),
            secondary_container: lerp_c3(&self.secondary_container, &target.secondary_container, t),
            on_secondary_container: lerp_c3(&self.on_secondary_container, &target.on_secondary_container, t),
            tertiary: lerp_c3(&self.tertiary, &target.tertiary, t),
            on_tertiary: lerp_c3(&self.on_tertiary, &target.on_tertiary, t),
            tertiary_container: lerp_c3(&self.tertiary_container, &target.tertiary_container, t),
            on_tertiary_container: lerp_c3(&self.on_tertiary_container, &target.on_tertiary_container, t),
            error: lerp_c3(&self.error, &target.error, t),
            on_error: lerp_c3(&self.on_error, &target.on_error, t),
            error_container: lerp_c3(&self.error_container, &target.error_container, t),
            on_error_container: lerp_c3(&self.on_error_container, &target.on_error_container, t),
            surface: lerp_c3(&self.surface, &target.surface, t),
            on_surface: lerp_c3(&self.on_surface, &target.on_surface, t),
            surface_variant: lerp_c3(&self.surface_variant, &target.surface_variant, t),
            on_surface_variant: lerp_c3(&self.on_surface_variant, &target.on_surface_variant, t),
            outline: lerp_c3(&self.outline, &target.outline, t),
            outline_variant: lerp_c3(&self.outline_variant, &target.outline_variant, t),
            background: lerp_c3(&self.background, &target.background, t),
            on_background: lerp_c3(&self.on_background, &target.on_background, t),
        }
    }
}

/// Colour theme configuration.
