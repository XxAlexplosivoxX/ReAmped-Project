//! Persistent application configuration stored as TOML.
//!
//! Configuration is loaded from the platform-specific config directory
//! (`~/.config/reamped/config.toml` on Linux).  When the file is missing or
//! corrupt, [`load_config`] falls back to [`AppConfig::default`].

use dirs_next::config_dir;
use std::path::PathBuf;
use serde::{Serialize, Deserialize};
use crate::keybindings::KeyBindings;

/// Returns the platform-specific path to the config file.
///
/// The directory is created if it does not exist.  On Linux this resolves to
/// `$XDG_CONFIG_HOME/reamped/config.toml` (usually `~/.config/reamped/config.toml`).
fn config_path() -> PathBuf {
    let mut path = config_dir().expect("No config dir");
    path.push("reamped");
    std::fs::create_dir_all(&path).ok();
    path.push("config.toml");
    path
}

/// Top-level application configuration.
///
/// All fields are serialised to and deserialised from TOML via Serde.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct AppConfig {
    /// Master volume (`0.0` – `1.0`).
    pub volume: f32,
    /// Start the UI in fullscreen mode.
    pub fullscreen: bool,
    /// Enable crossfade between tracks.
    pub crossfade_enabled: bool,
    /// Crossfade duration in seconds.
    pub crossfade_seconds: f32,
    /// Automatically trim leading silence from tracks.
    #[serde(default)]
    pub silence_trim_enabled: bool,
    /// Colour theme settings.
    pub theme: ThemeConfig,
    /// FFT window size for the spectrum analyser.
    pub fft_size: usize,
    /// Apply smoothing to the spectrum display.
    pub spectrum_smooth: bool,
    /// Use line-mode rendering for the spectrum.
    pub line_mode: bool,
    /// Use the legacy rendering style.
    pub old_style: bool,
    /// Number of bars in the spectrum visualiser.
    pub spectrum_bars_quantity: usize,
    /// Directories scanned for music files.
    pub music_dirs: Vec<std::path::PathBuf>,
    /// User-customisable keyboard bindings.
    pub keybindings: KeyBindings,
    /// EQ bass gain (0.0–2.0, default 1.0).
    #[serde(default = "default_eq_gain")]
    pub bass_val: f32,
    /// EQ mid gain (0.0–2.0, default 1.0).
    #[serde(default = "default_eq_gain")]
    pub mid_val: f32,
    /// EQ high gain (0.0–2.0, default 1.0).
    #[serde(default = "default_eq_gain")]
    pub high_val: f32,
    /// Stereo expander width (0.0–2.0, default 1.0).
    #[serde(default = "default_eq_gain")]
    pub width_val: f32,
    /// Target frames per second for the UI (when focused).
    #[serde(default = "default_fps")]
    pub target_fps: u32,
    /// Enable vsync (may cause freezes on Hyprland when switching workspaces).
    #[serde(default = "default_true")]
    pub vsync: bool,
    /// Play bit-perfect audio through direct ALSA hardware access
    /// (bypasses PulseAudio/PipeWire/dmix and software resampling).
    /// Falls back to the CPAL backend when unsupported or unavailable.
    #[serde(default)]
    pub bit_perfect_enabled: bool,
    /// ALSA device name for bit-perfect playback (e.g. `hw:0,0`).
    /// When empty, the first available `hw:` playback device is used.
    #[serde(default)]
    pub bit_perfect_device: String,
}

fn default_eq_gain() -> f32 { 1.0 }
fn default_fps() -> u32 { 60 }
fn default_true() -> bool { true }

/// Source of the colour theme palette.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum ThemeSource {
    /// Extract colours automatically from the current album cover.
    AlbumCover,
    /// Extract colours automatically from the system wallpaper.
    SystemWallpaper,
    /// Use manually configured colour roles.
    Manual,
}

